// Rasterize selected official Lucide SVGs for WeChat's native Image component.
// Only colors used by the UI are emitted; no icon font or runtime library.
const sharp = require('sharp')
const fs = require('fs')
const path = require('path')
const ts = require('typescript')

const sourceRoot = path.resolve(__dirname, '../src')
const iconsDir = path.join(sourceRoot, 'assets/icons')
const outputDir = path.join(iconsDir, 'lucide')
const packageRoot = path.dirname(require.resolve('lucide-static/package.json'))
const names = [
  'arrow-right', 'arrow-up', 'bell', 'camera', 'car-front', 'chart-no-axes-combined',
  'check', 'chevron-right', 'circle-check', 'circle-help', 'clock-3',
  'contact-round', 'credit-card', 'file-text', 'files', 'folder', 'folder-open',
  'hospital', 'house', 'id-card', 'inbox', 'info', 'loader-circle', 'lock-keyhole',
  'messages-square', 'plus', 'route', 'scale', 'settings', 'shield-check',
  'triangle-alert', 'undo-2', 'user-round', 'x',
]
const variants = new Map(names.map(name => [name, new Set(['#6B7280', '#8E8E93'])]))

function filesIn(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const file = path.join(dir, entry.name)
    return entry.isDirectory() ? filesIn(file) : [file]
  })
}

function stringsIn(node) {
  const values = []
  function visit(current) {
    if (ts.isStringLiteral(current)) values.push(current.text)
    ts.forEachChild(current, visit)
  }
  visit(node)
  return values
}

for (const file of filesIn(sourceRoot).filter(file => file.endsWith('.tsx'))) {
  const source = ts.createSourceFile(file, fs.readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.TSX)
  const pageNames = stringsIn(source).filter(name => variants.has(name))
  function visit(node) {
    if ((ts.isJsxSelfClosingElement(node) || ts.isJsxOpeningElement(node)) && node.tagName.getText(source) === 'Icon') {
      const props = Object.fromEntries(node.attributes.properties.filter(ts.isJsxAttribute).map(prop => [prop.name.getText(source), prop.initializer]))
      const literalNames = props.name ? stringsIn(props.name).filter(name => variants.has(name)) : []
      const usedNames = literalNames.length ? literalNames : pageNames.length ? pageNames : names
      const colors = props.color ? stringsIn(props.color).filter(color => /^#[0-9a-f]{6}$/i.test(color)) : ['#6B7280']
      for (const name of usedNames) for (const color of colors) variants.get(name).add(color.toUpperCase())
    }
    ts.forEachChild(node, visit)
  }
  visit(source)
}

const tabs = { case: 'house', agent: 'messages-square', profile: 'user-round' }
function svgFor(name, color) {
  return fs.readFileSync(path.join(packageRoot, 'icons', `${name}.svg`), 'utf8')
    .replace('stroke="currentColor"', `stroke="${color}"`)
}

async function convertIcons() {
  fs.mkdirSync(outputDir, { recursive: true })
  fs.copyFileSync(path.join(packageRoot, 'LICENSE'), path.join(outputDir, 'LICENSE'))
  const imports = []
  const entries = []
  let count = 0
  for (const [name, colors] of variants) {
    const assets = []
    for (const color of [...colors].sort()) {
      const filename = `${name}-${color.slice(1).toLowerCase()}.png`
      await sharp(Buffer.from(svgFor(name, color))).resize(192, 192).png().toFile(path.join(outputDir, filename))
      const variable = `icon${count++}`
      imports.push(`import ${variable} from '../../assets/icons/lucide/${filename}'`)
      assets.push(`    '${color}': ${variable},`)
    }
    entries.push(`  '${name}': {\n${assets.join('\n')}\n  },`)
  }
  fs.writeFileSync(path.join(sourceRoot, 'components/Icon/assets.ts'), [
    '// Generated by npm run convert:icons. Source: lucide-static (ISC license).',
    ...imports,
    '',
    'export const iconAssets: Record<string, Record<string, string>> = {',
    ...entries,
    '}',
    '',
  ].join('\n'))
  for (const [tab, name] of Object.entries(tabs)) {
    for (const active of [false, true]) {
      const base = `${tab}${active ? '-active' : ''}`
      const svg = svgFor(name, active ? '#4D6BFE' : '#9CA3AF')
      fs.writeFileSync(path.join(iconsDir, `${base}.svg`), svg)
      await sharp(Buffer.from(svg)).resize(96, 96).png().toFile(path.join(iconsDir, `${base}.png`))
    }
  }
  console.log(`Generated ${count} Lucide assets and 6 navigation icons.`)
}

convertIcons().catch(error => {
  console.error(error)
  process.exitCode = 1
})
